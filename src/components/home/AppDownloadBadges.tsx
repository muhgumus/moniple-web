const platformNames: Record<Platform, string> = {
  web: "Web",
  ios: "iOS",
  android: "Android",
  macos: "macOS",
  windows: "Windows",
  linux: "Linux",
};

function Badge({ badge }: { badge: AppBadge }) {
  const isAvailable = badge.state === "available";
  const name = platformNames[badge.platform];

  const content = (
    <div className="flex items-center gap-3">
      <div className="w-8 h-8 text-primary flex-shrink-0">
        {platformIcons[badge.platform]}
      </div>
      <div className="text-left">
        <div className="text-sm font-semibold text-dark dark:text-white">
          {name}
        </div>
        <div
          className={`text-xs font-medium ${
            isAvailable ? "text-emerald-500" : "text-amber-500"
          }`}
        >
          {badge.label}
        </div>
      </div>
    </div>
  );

  const baseClasses =
    "flex items-center gap-3 bg-white dark:bg-gray-800 rounded-xl px-5 py-3 shadow-md ring-1 ring-gray-200 dark:ring-gray-700 transition-all duration-200";

  if (isAvailable && badge.href) {
    return (
      <a
        href={badge.href}
        target="_blank"
        rel="noopener noreferrer"
        className={`${baseClasses} hover:ring-primary hover:shadow-lg cursor-pointer`}
      >
        {content}
      </a>
    );
  }

  return <div className={`${baseClasses} opacity-80`}>{content}</div>;
}

export default function AppDownloadBadges({ badges }: { badges: AppBadge[] }) {
  return (
    <div className="flex flex-wrap items-center justify-center gap-3 sm:gap-4">
      {badges.map((b) => (
        <Badge key={b.platform} badge={b} />
      ))}
    </div>
  );
}
